"""
verify_parity.py — regression check: does portal_pricing.py reproduce the portal's
offer.js exactly? Compares portal_pricing.evaluate() against oracle_grid.json
(generated by make_oracle.js from the REAL offer.js).

Run:  node make_oracle.js && python3 verify_parity.py
A clean run prints "PARITY OK". Any mismatch is a bug in portal_pricing or a
rules.json that drifted from the oracle grid.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import portal_pricing  # noqa: E402

grid_path = os.path.join(HERE, 'oracle_grid.json')
if not os.path.exists(grid_path):
    sys.exit("oracle_grid.json missing — run `node make_oracle.js` first (needs ~/kts-seller-app).")

data = json.load(open(grid_path))
rows = data['rows']
mism = []
for r in rows:
    comp = {'clValue': r['value'], 'grade': r['grade'], 'sport': r['sport'], 'cert': r['cert']}
    res = portal_pricing.evaluate(comp)
    dec = res['decision']
    off = res['offer']
    o_dec, o_off = r['decision'], r['offer']
    ok_dec = (dec == o_dec)
    ok_off = (off is None and o_off is None) or (off is not None and o_off is not None and abs(off - o_off) < 0.005)
    if not (ok_dec and ok_off):
        mism.append((r, {'decision': dec, 'offer': off}))

print(f"checked {len(rows)} oracle points")
if mism:
    print(f"MISMATCHES: {len(mism)}")
    for r, got in mism[:40]:
        print("  ", r['sport'], '$' + str(r['value']), 'g' + str(r['grade']), 'cert', r['cert'],
              '| oracle', r['decision'], r['offer'], '| portal_pricing', got['decision'], got['offer'])
    sys.exit(1)
print("PARITY OK — portal_pricing.py reproduces offer.js on every point.")
